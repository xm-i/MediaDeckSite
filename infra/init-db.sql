-- MediaDeckSite 用 PostgreSQL 初期構築スクリプト
-- 実行前に 'CHANGE_ME_STRONG_PASSWORD' を安全なパスワードへ変更してください。

CREATE USER mediadeck WITH PASSWORD 'CHANGE_ME_STRONG_PASSWORD';
CREATE DATABASE mediadeck OWNER mediadeck ENCODING 'UTF8';

\connect mediadeck

ALTER SCHEMA public OWNER TO mediadeck;

SET ROLE mediadeck;

CREATE TABLE IF NOT EXISTS feedbacks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(32) NOT NULL,
    title VARCHAR(500) NOT NULL,
    description TEXT NOT NULL,
    contact VARCHAR(500),
    environment_info TEXT,
    log_content TEXT,
    screenshot_data BYTEA,
    screenshot_mime_type VARCHAR(32),
    screenshot_extension VARCHAR(16),
    submitted_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    client_ip VARCHAR(64)
);

CREATE INDEX IF NOT EXISTS ix_feedbacks_submitted_at ON feedbacks (submitted_at);
CREATE INDEX IF NOT EXISTS ix_feedbacks_category ON feedbacks (category);

RESET ROLE;
